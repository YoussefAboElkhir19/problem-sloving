


// return number 1 => one 
function SwitchCase(num) {



    switch (num) {

        case 1:
            return "One";
            break;
        case 2:
            return "Two";
            break;
        case 3:
            return "Three";
            break;
        default:
            return "Number Out Of Scope!!!"

    }

}

console.log(SwitchCase(1));